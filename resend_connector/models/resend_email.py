"""
One row per email delivered through Resend.

The row keeps the delivery state, the Resend identifiers and the event history.
It survives the deletion of the Odoo mail.mail record, which is why the status
lives here and is only mirrored on mail.mail for the standard views.
"""

import logging
from datetime import timedelta

from odoo import api, fields, models

_logger = logging.getLogger(__name__)

#: Delivery states, ordered from the earliest to the latest. A webhook event may
#: never move a record backwards, except for terminal states.
STATE_RANK = {
    'sending': 0,
    'scheduled': 1,
    'sent': 2,
    'accepted': 3,
    'delayed': 4,
    'delivered': 5,
    'opened': 6,
    'clicked': 7,
}

TERMINAL_STATES = ('bounced', 'complained', 'failed')

#: Ranking between terminal states: a complaint outranks a bounce, which
#: outranks a generic failure. A terminal state is never left.
TERMINAL_RANK = {'failed': 80, 'bounced': 90, 'complained': 100}

EVENT_TO_STATE = {
    'email.sent': 'sent',
    'email.scheduled': 'scheduled',
    'email.accepted': 'accepted',
    'email.delivered': 'delivered',
    'email.delivery_delayed': 'delayed',
    'email.opened': 'opened',
    'email.clicked': 'clicked',
    'email.bounced': 'bounced',
    'email.complained': 'complained',
    'email.failed': 'failed',
}


class ResendEmail(models.Model):
    _name = 'resend.email'
    _description = 'Resend Email'
    _order = 'id desc'
    _rec_name = 'subject'

    subject = fields.Char(string='Subject', readonly=True)
    resend_message_id = fields.Char(
        string='Resend Message-ID', readonly=True, index='btree',
        copy=False, help='Identifier returned by the Resend API.')
    rfc_message_id = fields.Char(
        string='RFC Message-ID', readonly=True, index='btree', copy=False,
        help='Message-Id header of the email built by Odoo.')
    actual_message_id = fields.Char(
        string='Message-ID at Resend', readonly=True, index='btree', copy=False,
        help='The RFC Message-Id that Resend actually used: it replaces the '
             'Message-Id generated by Odoo, so replies reference this one. Used '
             'to map an inbound reply back to the Odoo thread.')
    send_key = fields.Char(
        string='Send Key', readonly=True, index='btree', copy=False,
        help='Stable key of one actual delivery: the RFC Message-Id plus its '
             'recipients. Odoo may split a single mail.mail into several emails '
             '(one per recipient); each of them is tracked separately and a '
             'retry of the same email reuses its row.')
    mail_mail_id = fields.Many2one(
        'mail.mail', string='Odoo Email', readonly=True, index='btree_not_null',
        ondelete='set null', copy=False)
    mail_server_id = fields.Many2one(
        'ir.mail_server', string='Mail Server', readonly=True, ondelete='set null')
    company_id = fields.Many2one(
        'res.company', string='Company', readonly=True,
        default=lambda self: self.env.company)
    from_email = fields.Char(string='From', readonly=True)
    to_emails = fields.Text(string='To', readonly=True)
    cc_emails = fields.Text(string='Cc', readonly=True)
    bcc_emails = fields.Text(string='Bcc', readonly=True)
    state = fields.Selection([
        ('sending', 'Sending'),
        ('scheduled', 'Scheduled'),
        ('sent', 'Sent'),
        ('accepted', 'Accepted'),
        ('delayed', 'Delivery Delayed'),
        ('delivered', 'Delivered'),
        ('opened', 'Opened'),
        ('clicked', 'Clicked'),
        ('bounced', 'Bounced'),
        ('complained', 'Complained (Spam)'),
        ('failed', 'Failed'),
    ], string='Status', default='sending', readonly=True, index=True, copy=False)
    status_date = fields.Datetime(string='Status Date', readonly=True, copy=False)
    last_event_type = fields.Char(string='Last Event', readonly=True, copy=False)
    error = fields.Text(string='Error', readonly=True, copy=False)
    error_code = fields.Char(string='Error Code', readonly=True, copy=False)
    transient_failure = fields.Boolean(
        string='Transient Failure', readonly=True, copy=False,
        help='A transient failure (network, rate limit, 5xx) may be retried automatically.')
    retry_count = fields.Integer(string='Retries', default=0, readonly=True, copy=False)
    event_ids = fields.One2many(
        'resend.email.event', 'email_id', string='Events', readonly=True)
    event_count = fields.Integer(compute='_compute_event_count', string='Events Count')

    _resend_message_id_uniq = models.Constraint(
        'UNIQUE(resend_message_id)',
        'A Resend email with this identifier already exists.',
    )
    _send_key_uniq = models.Constraint(
        'UNIQUE(send_key)', 'This delivery is already tracked.')

    @api.depends('event_ids')
    def _compute_event_count(self):
        for record in self:
            record.event_count = len(record.event_ids)

    @api.model
    def _state_rank(self, state):
        if state in TERMINAL_STATES:
            return 1000 + TERMINAL_RANK.get(state, 0)
        return STATE_RANK.get(state, 0)

    def _worst_state(self):
        """Worst state across the deliveries of one mail.mail record."""
        self.ensure_one()
        if not self:
            return False
        return max(self, key=lambda record: self._state_rank(record.state))

    def _auto_init(self):
        result = super()._auto_init()
        # Refresh the access rules on install/upgrade (version independent).
        self.env['resend.connector']._ensure_access_rights()
        return result

    # ------------------------------------------------------------------ events
    def _apply_event(self, event_type, data=None, event=None):
        """Apply a Resend webhook event to the tracking record.

        States are ranked: a late "opened" event never rolls a record back to
        "sent". Terminal states (bounced, complained, failed) always apply.
        """
        data = data or {}
        new_state = EVENT_TO_STATE.get(event_type)
        if not new_state:
            return False
        for record in self:
            vals = {'last_event_type': event_type}
            current_rank = STATE_RANK.get(record.state, 0)
            new_rank = STATE_RANK.get(new_state, 0)
            if record.state in TERMINAL_STATES:
                # Already failed for good: only a "worse" terminal state applies.
                applies = (new_state in TERMINAL_STATES
                           and TERMINAL_RANK[new_state] > TERMINAL_RANK[record.state])
            elif new_state in TERMINAL_STATES:
                applies = True
            else:
                applies = new_rank > current_rank
            if applies:
                vals.update({'state': new_state, 'status_date': fields.Datetime.now()})
                if new_state not in TERMINAL_STATES:
                    vals.update({'error': False, 'error_code': False,
                                 'transient_failure': False})
            if event_type == 'email.bounced':
                bounce = data.get('bounce') or {}
                vals.update({
                    'error': bounce.get('message') or data.get('message') or 'Bounced',
                    'error_code': bounce.get('type') or data.get('error_code') or 'bounced',
                    'transient_failure': False,
                })
            elif event_type == 'email.complained':
                vals.update({'error': 'Recipient marked the message as spam',
                             'error_code': 'complained', 'transient_failure': False})
            elif event_type == 'email.failed':
                vals.update({
                    'error': data.get('message') or data.get('reason') or 'Delivery failed',
                    'error_code': data.get('error_code') or data.get('name') or 'failed',
                    'transient_failure': False,
                })
            elif event_type == 'email.delivery_delayed':
                vals.update({'transient_failure': True})
            record.sudo().write(vals)
            if applies:
                record._sync_mail_mail_state(new_state)
            record.mail_mail_id.sudo()._resend_sync_from_tracking()
        return True

    def _sync_mail_mail_state(self, state):
        """Reflect the Resend state on the underlying Odoo records.

        One mail.mail can produce several deliveries (Odoo splits notifications
        per recipient): the mirror fields on mail.mail always show the worst
        state of all its deliveries.
        """
        for record in self:
            mail = record.mail_mail_id.sudo().exists()
            if not mail:
                continue
            if state == 'bounced':
                mail.write({
                    'state': 'exception',
                    'failure_type': 'mail_smtp',
                    'failure_reason': record.error or 'Bounced by Resend',
                })
                record._sync_notifications('bounce', 'mail_bounce', record.error)
            elif state == 'complained':
                mail.write({
                    'state': 'exception',
                    'failure_type': 'mail_spam',
                    'failure_reason': record.error or 'Marked as spam',
                })
                record._sync_notifications('canceled', 'mail_spam', record.error)
            elif state == 'failed':
                mail.write({
                    'state': 'exception',
                    'failure_type': 'mail_smtp',
                    'failure_reason': record.error or 'Failed by Resend',
                })
            elif state in ('delivered', 'opened', 'clicked'):
                record._sync_notifications('sent', False, False)
            mail._resend_sync_from_tracking()

    def _sync_notifications(self, status, failure_type, reason):  # noqa: D401
        notifications = self.env['mail.notification'].sudo().search([
            ('mail_mail_id', 'in', self.mapped('mail_mail_id').ids),
            ('notification_type', '=', 'email'),
        ])
        if notifications:
            notifications.write({
                'notification_status': status,
                'failure_type': failure_type or False,
                'failure_reason': reason or False,
            })

    # ---------------------------------------------------------------- utilities
    @api.model
    def _find_by_resend_id(self, resend_message_id):
        if not resend_message_id:
            return self.browse()
        return self.sudo().search([('resend_message_id', '=', resend_message_id)], limit=1)

    # ------------------------------------------------------------------- crons
    @api.model
    def _cron_retry_failed(self):
        """Re-queue emails that failed for a transient Resend error."""
        connector = self.env['resend.connector']
        config = connector._get_config()
        max_retry = config['auto_retry_max']
        if max_retry <= 0:
            return False
        delay = fields.Datetime.now() - timedelta(minutes=config['retry_delay_minutes'])
        emails = self.sudo().search([
            ('state', '=', 'failed'),
            ('transient_failure', '=', True),
            ('retry_count', '<', max_retry),
            ('mail_mail_id', '!=', False),
            ('status_date', '<=', delay),
        ], limit=200)
        if not emails:
            return False
        mails = emails.mapped('mail_mail_id').exists()
        if mails:
            mails.sudo().write({'state': 'outgoing'})
            _logger.info('Resend: re-queued %s transient failure(s)', len(mails))
        return True

    @api.model
    def _cron_reconcile_status(self):
        """Poll Resend for emails whose webhooks never arrived."""
        connector = self.env['resend.connector']
        if not connector._get_config()['api_key']:
            return False
        horizon = fields.Datetime.now() - timedelta(hours=1)
        emails = self.sudo().search([
            ('state', 'in', ('sent', 'accepted', 'delayed')),
            ('resend_message_id', '!=', False),
            ('status_date', '<=', horizon),
        ], limit=100, order='status_date asc')
        if not emails:
            return False
        client = connector._get_client()
        last_event_map = {
            'delivered': 'email.delivered',
            'opened': 'email.opened',
            'clicked': 'email.clicked',
            'bounced': 'email.bounced',
            'complained': 'email.complained',
            'delivery_delayed': 'email.delivery_delayed',
            'failed': 'email.failed',
            'sent': 'email.sent',
            'scheduled': 'email.scheduled',
            'suppressed': 'email.suppressed',
        }
        for email in emails:
            try:
                answer = client.get_email(email.resend_message_id)
            except Exception:  # noqa: BLE001 - network hiccup: retry next hour
                _logger.info('Resend: could not reconcile email %s', email.id,
                             exc_info=True)
                continue
            last_event = (answer or {}).get('last_event')
            event_type = last_event_map.get(last_event)
            if event_type:
                email._apply_event(event_type, answer or {})
            message_id = (answer or {}).get('message_id')
            if message_id and message_id != email.actual_message_id:
                email.write({'actual_message_id': message_id})
            email.write({'status_date': fields.Datetime.now()})
        return True

    @api.model
    def _cron_gc(self):
        """Purge old tracking data (keeps the database small)."""
        now = fields.Datetime.now()
        self.env['resend.webhook.event'].sudo().search([
            ('state', 'in', ('processed', 'ignored', 'failed')),
            ('received_date', '<', now - timedelta(days=30)),
        ]).unlink()
        self.env['resend.email.event'].sudo().search([
            ('event_date', '<', now - timedelta(days=90)),
        ]).unlink()
        self.sudo().search([
            ('state', 'in', ('failed', 'bounced', 'complained')),
            ('create_date', '<', now - timedelta(days=180)),
        ]).unlink()
        return True

    def action_retry(self):
        """Re-queue the linked Odoo email (Odoo retry semantics)."""
        mails = self.mapped('mail_mail_id').exists()
        if not mails:
            return False
        mails.action_retry()
        self.sudo().write({'state': 'sending', 'error': False, 'error_code': False})
        return True