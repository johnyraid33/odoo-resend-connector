"""
Settings screen in Settings > Discuss > Resend and the actions on it.
"""

import logging

from odoo import _, api, fields, models
from odoo.exceptions import UserError

from .compat import param_get_str, param_set
from .resend_client import ResendAPIError

_logger = logging.getLogger(__name__)


class ResConfigSettings(models.TransientModel):
    _inherit = 'res.config.settings'

    # --- master switch / credentials ---
    resend_enabled = fields.Boolean(
        string='Send emails through Resend',
        config_parameter='resend.enabled',
        help="Master switch. When enabled, every outgoing mail server flagged "
             "with 'Use Resend API' delivers through Resend instead of SMTP. "
             "Turn it off to fall back to SMTP instantly, without restarting.",
    )
    resend_api_key = fields.Char(
        string='Resend API Key',
        config_parameter='resend.api_key',
        help="Resend API key (re_...). A 'Sending access' key is enough for "
             "outgoing email; domains and webhooks need 'Full access'.",
    )
    resend_from_email = fields.Char(
        string='From Address',
        config_parameter='resend.from_email',
        help="Address on a domain verified in Resend, e.g. no-reply@mg.example.com.",
    )
    resend_from_mode = fields.Selection([
        ('unverified', 'Only when the sender domain is not verified in Resend'),
        ('always', 'Always'),
        ('off', 'Never - use the address Odoo chooses'),
    ], string='Rewrite From', config_parameter='resend.from_mode', default='unverified',
        help="Odoo may pick a sender address on a domain that Resend cannot use "
             "(users' personal addresses, catchall...). This option replaces it "
             "with the From address above, and keeps the original sender in "
             "Reply-To so that replies still reach the right person.")

    # --- webhook ---
    resend_webhook_secret = fields.Char(
        string='Webhook Signing Secret',
        config_parameter='resend.webhook_secret',
        help="whsec_... secret shown by Resend when the webhook is created. "
             "Several secrets may be separated by commas during a rotation.",
    )
    resend_webhook_url = fields.Char(
        string='Webhook URL', compute='_compute_resend_webhook_url',
        help="Register this URL in Resend (Webhooks > Add endpoint) and select "
             "the email events.")
    resend_webhook_configured = fields.Boolean(
        string='Webhook Configured', compute='_compute_resend_webhook_configured')

    # --- advanced ---
    resend_inline_images_mode = fields.Selection([
        ('cid', 'Keep Content-ID references (recommended)'),
        ('data_uri', 'Embed images as data URIs'),
        ('attachment', 'Send as plain attachments'),
    ], string='Inline Images', config_parameter='resend.inline_images_mode',
        default='cid')
    resend_preserve_message_id = fields.Boolean(
        string='Send Odoo Message-ID', config_parameter='resend.preserve_message_id',
        default=True,
        help="Forward the Message-Id generated by Odoo as a custom header. Resend "
             "assigns its own Message-Id anyway: the module tracks it and maps "
             "replies back to the right Odoo thread automatically. Disable this "
             "only if Resend rejects the header.")
    resend_store_payloads = fields.Boolean(
        string='Store Webhook Payloads', config_parameter='resend.store_webhook_payloads',
        default=True,
        help="Keep the raw webhook JSON for debugging (recommended).")
    resend_save_inbound_original = fields.Boolean(
        string='Keep Original Inbound Messages',
        config_parameter='resend.save_inbound_original',
        help="Attach the original .eml to every imported incoming email.")
    resend_auto_retry_max = fields.Integer(
        string='Auto-Retry Transient Failures',
        config_parameter='resend.auto_retry_max', default=3,
        help="Number of automatic retries for emails that failed because of a "
             "transient Resend error (network, rate limit, 5xx). 0 disables it.")
    resend_retry_delay = fields.Integer(
        string='Retry Delay (minutes)', config_parameter='resend.retry_delay_minutes',
        default=15)
    resend_rate_limit = fields.Integer(
        string='Requests / second', config_parameter='resend.rate_limit', default=8,
        help="Resend allows 10 requests per second per team, shared by every key. "
             "Keep this value slightly below the limit.")
    resend_webhook_tolerance = fields.Integer(
        string='Webhook Tolerance (seconds)',
        config_parameter='resend.webhook_tolerance', default=300,
        help="Maximum age difference accepted for the webhook timestamp.")
    resend_base_url = fields.Char(
        string='API Base URL', config_parameter='resend.base_url',
        help="Only change it to use a proxy or a mock server. "
             "Default: https://api.resend.com")
    resend_public_base_url = fields.Char(
        string='Public Base URL', config_parameter='resend.public_base_url',
        help="Public URL of this Odoo instance used to build the webhook URL. "
             "Leave empty to use the system 'web.base.url'.")

    # --- computed status ---
    resend_status = fields.Selection([
        ('not_configured', 'Not configured'),
        ('ready', 'Ready'),
        ('not_verified', 'No verified domain'),
    ], string='Resend Status', compute='_compute_resend_status')
    resend_domain_count = fields.Integer(
        string='Domains', compute='_compute_resend_status')
    resend_verified_domains = fields.Char(
        string='Verified Domains', compute='_compute_resend_status')

    @api.depends('resend_public_base_url')
    def _compute_resend_webhook_url(self):
        for record in self:
            record.resend_webhook_url = record.env['resend.connector']._get_webhook_url()

    @api.depends('resend_webhook_secret')
    def _compute_resend_webhook_configured(self):
        for record in self:
            record.resend_webhook_configured = bool(record.resend_webhook_secret)

    @api.depends('resend_api_key', 'resend_from_email')
    def _compute_resend_status(self):
        domains = self.env['resend.domain'].sudo().search([])
        verified = domains.filtered(lambda d: d.status == 'verified')
        key = param_get_str(self.env['ir.config_parameter'].sudo(), 'resend.api_key')
        for record in self:
            if not key:
                record.resend_status = 'not_configured'
            elif not verified:
                record.resend_status = 'not_verified'
            else:
                record.resend_status = 'ready'
            record.resend_domain_count = len(domains)
            record.resend_verified_domains = ', '.join(verified.mapped('name'))

    # ------------------------------------------------------------------ actions
    def action_resend_test_connection(self):
        self.ensure_one()
        try:
            summary = self.env['resend.connector']._check_connection()
        except ResendAPIError as exc:
            raise UserError(exc.as_user_message()) from exc
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _('Resend connection'),
                'message': _('Connection OK - %(count)s domain(s), verified: %(domains)s',
                             count=summary['domains_count'],
                             domains=', '.join(summary['verified']) or _('none')),
                'type': 'success',
                'sticky': False,
            },
        }

    def action_resend_sync_domains(self):
        self.ensure_one()
        self.env['resend.domain']._sync_all()
        return self.action_resend_test_connection()

    def action_resend_create_webhook(self):
        """Create (or update) the webhook endpoint in Resend and store its secret."""
        self.ensure_one()
        connector = self.env['resend.connector']
        client = connector._get_client()
        url = connector._get_webhook_url()
        events = list(self.env['resend.webhook.event'].WEBHOOK_EVENTS)
        try:
            answer = client.list_webhooks()
        except ResendAPIError as exc:
            raise UserError(exc.as_user_message()) from exc
        hooks = answer.get('data') if isinstance(answer, dict) else (answer or [])
        hook = next((h for h in hooks if h.get('endpoint') == url), None)
        stored_secret = hook.get('signing_secret') if hook else None
        try:
            if hook:
                hook = dict(hook, **client.update_webhook(
                    hook['id'], {'events': events, 'status': 'enabled'}))
            else:
                hook = client.create_webhook(url, events)
        except ResendAPIError as exc:
            raise UserError(exc.as_user_message()) from exc
        secret = hook.get('signing_secret') or stored_secret
        ICP = self.env['ir.config_parameter'].sudo()
        if secret:
            param_set(ICP, 'resend.webhook_secret', secret)
        param_set(ICP, 'resend.webhook_id', hook.get('id') or '')
        connector._invalidate_config_cache()
        return {
            'type': 'ir.actions.client',
            'tag': 'display_notification',
            'params': {
                'title': _('Resend webhook'),
                'message': _('Webhook ready: %s', url) if secret else
                           _('Webhook exists but Resend did not return its secret. '
                             'Copy it from the Resend dashboard.'),
                'type': 'success' if secret else 'warning',
                'sticky': not bool(secret),
                'next': {'type': 'ir.actions.act_window_close'},
            },
        }

    def action_resend_open_documentation(self):
        self.ensure_one()
        return {
            'type': 'ir.actions.act_url',
            'url': '/resend/documentation',
            'target': 'self',
        }

    def action_resend_open_domains(self):
        self.ensure_one()
        return self.env['ir.actions.act_window']._for_xml_id(
            'resend_connector.action_resend_domain')